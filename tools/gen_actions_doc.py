#!/usr/bin/env python3
"""从代码生成动作/对象参考文档（docs/ACTIONS.md），保证文档与实现同步。

用法：./scripts/csva tools/gen_actions_doc.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from cs_video_agent.engine.actions import ACTION_SPECS  # noqa: E402
from cs_video_agent.engine.actions_net import _DESC as DESC_NET  # noqa: E402
from cs_video_agent.engine.actions_text import _DESC as DESC_TEXT  # noqa: E402
from cs_video_agent.visualkit.models import SUPPORTED_INVARIANTS  # noqa: E402
from cs_video_agent.visualkit.views import _ALLOWED  # noqa: E402

OBJ_META = {
    "socket_grid": ("大规模连接网格（select/poll 扫描用）", "center"),
    "socket_stack": ("带 fd 标签的少量连接（epoll 场景用）", "<fd>，如 sockets.5"),
    "ready_queue": ("就绪队列 ready list（与 kernel 共享同一 ReadyList 模型）", "in/bottom/center"),
    "kernel_panel": ("内核面板 + interest list 徽章容器", "left/right/top/bottom/center"),
    "worker_box": ("应用进程框（epoll_wait 状态文字）", "left/right/top/bottom/center"),
    "event_flow": ("箭头集合：arrows=[{id,from,to,color,faint,tip}]，端点用 obj.anchor 引用；必须放在 objects 最后", "（无）"),
}

INV_DESC = {
    "only_ready_sockets_are_returned": "wait() 只返回曾以就绪态入队的 fd",
    "unregistered_sockets_never_enqueued": "未注册进 interest list 的 fd 不会被入队",
    "ready_list_no_duplicates": "就绪队列里同一 fd 不重复",
    "scan_checks_every_socket": "每次 grid_scan 恰好把网格里所有连接各检查一遍",
}


def main() -> int:
    desc = {**DESC_TEXT, **DESC_NET}
    lines = [
        "# Scene IR 参考：对象 / 动作 / 不变量",
        "",
        "> AUTO-GENERATED by `tools/gen_actions_doc.py` —— 改动作或视图后重新生成，勿手改。",
        "",
        "## 场景对象（objects[].type）",
        "",
        "| type | 构造参数（params） | 说明 | 锚点（anchor） |",
        "|---|---|---|---|",
    ]
    for t, allowed in _ALLOWED.items():
        params = ", ".join(sorted(allowed)) or "-"
        note, anchors = OBJ_META.get(t, ("", ""))
        lines.append(f"| `{t}` | {params} | {note} | {anchors} |")

    lines += [
        "",
        "锚点引用格式：`对象id.锚点名`，例如 `kernel.right`、`sockets.5`、`queue.in`。",
        "",
        "## 动作（beats[].actions[].action）",
        "",
        "| action | 必选参数 | 可选参数 | 说明 |",
        "|---|---|---|---|",
    ]
    for name in sorted(ACTION_SPECS):
        spec = ACTION_SPECS[name]
        req = ", ".join(f"`{k}`" for k in spec["required"]) or "-"
        opt = ", ".join(f"`{k}`" for k in spec["optional"]) or "-"
        lines.append(f"| `{name}` | {req} | {opt} | {desc.get(name, '')} |")

    lines += [
        "",
        "## 语义不变量（scene.invariants）",
        "",
        "回放校验（engine/replay.py）支持的取值：",
        "",
    ]
    for inv in sorted(SUPPORTED_INVARIANTS):
        lines.append(f"- `{inv}`：{INV_DESC.get(inv, '')}")

    lines += [
        "",
        "## 节拍（beats[]）字段",
        "",
        "- `id`：幕内唯一；`narration`：字幕文本（None 表示无解说的纯动作节拍）；",
        "  `dwell`：动作之后留给观众阅读的停顿秒数；`actions`：顺序执行的动作列表。",
        "- 阅读速度建议：解说字数 /（动作时长 + dwell）控制在 ~4.5 字/秒以下。",
        "",
    ]

    out = ROOT / "docs" / "ACTIONS.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"written {out} ({len(ACTION_SPECS)} actions, "
          f"{len(_ALLOWED)} object types)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
